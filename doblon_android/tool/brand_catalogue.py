"""Regenerates lib/brand_catalogue.dart from the OpenStreetMap Name Suggestion Index (BSD-3, see
third_party/name-suggestion-index/LICENSE.md).

Usage: python tool/brand_catalogue.py <folder with the NSI data/brands JSON files, named like shop_clothes.json>
Download each file from https://raw.githubusercontent.com/osmlab/name-suggestion-index/main/data/brands/<group>/<type>.json

Kept: brands present in Spain or worldwide/Europe ("es", "001", "150"), mapped to Doblón's starter categories,
and only when the brand belongs to a single category (Carrefour, a supermarket and a petrol station, is left out).
One example per brand: the experiment of 12/11/2026 (Obsidian, «IA de clasificación de movimientos») showed that
more formats per brand bring wrong proposals for Bizum and transfers.
"""
import glob
import json
import os
import re
import sys

CATEGORY = {
    'supermarket': 'Supermercado', 'shop_supermarket': 'Supermercado', 'shop_convenience': 'Supermercado',
    'amenity_restaurant': 'Restaurantes', 'amenity_fast_food': 'Restaurantes', 'amenity_cafe': 'Restaurantes',
    'amenity_bar': 'Restaurantes', 'amenity_ice_cream': 'Restaurantes',
    'amenity_fuel': 'Coche', 'shop_car_repair': 'Coche', 'shop_tyres': 'Coche',
    'amenity_pharmacy': 'Farmacia', 'shop_optician': 'Salud',
    'shop_clothes': 'Ropa', 'shop_shoes': 'Ropa',
    'shop_electronics': 'Compras', 'shop_department_store': 'Compras', 'shop_doityourself': 'Compras',
    'shop_furniture': 'Compras', 'shop_sports': 'Compras', 'shop_toys': 'Compras', 'shop_books': 'Compras',
    'shop_variety_store': 'Compras', 'shop_chemist': 'Compras', 'shop_cosmetics': 'Compras', 'shop_perfumery': 'Compras',
    'shop_pet': 'Mascotas', 'shop_mobile_phone': 'Internet y móvil', 'amenity_cinema': 'Ocio', 'tourism_hotel': 'Viajes',
}
REGIONS = {'es', '001', '150'}


def main(folder):
    found = {}
    for path in glob.glob(os.path.join(folder, '*.json')):
        category = CATEGORY.get(os.path.basename(path)[:-5])
        if not category:
            continue
        for item in json.load(open(path, encoding='utf-8')).get('items', []):
            if not REGIONS & {str(x) for x in item.get('locationSet', {}).get('include', [])}:
                continue
            tags = item.get('tags', {})
            name = (tags.get('brand') or tags.get('name') or item.get('displayName') or '').strip()
            # The model reads words of two letters or more; a name without any teaches nothing.
            if any(len(w) >= 2 for w in re.findall(r'[^\W\d_]+', name)):
                found.setdefault(name, set()).add(category)
    by_category = {}
    for name, categories in found.items():
        if len(categories) == 1:
            by_category.setdefault(next(iter(categories)), []).append(name)
    lines = [
        '// Generated by tool/brand_catalogue.py from the OpenStreetMap Name Suggestion Index.',
        '// Copyright name-suggestion-index contributors, BSD 3-Clause: third_party/name-suggestion-index/LICENSE.md',
        '// Do not edit by hand.',
        '',
        '/// Real brands present in Spain, by Doblón starter category. Starting examples for the category model.',
        'const brandCatalogue = <String, List<String>>{',
    ]
    for category in sorted(by_category):
        # A JSON string is a valid Dart string once `$` is escaped (names may contain quotes or apostrophes).
        names = ', '.join(json.dumps(n, ensure_ascii=False).replace('$', r'\$') for n in sorted(by_category[category], key=str.lower))
        lines.append(f"  '{category}': [{names}],")
    lines.append('};')
    out = os.path.join(os.path.dirname(__file__), '..', 'lib', 'brand_catalogue.dart')
    open(out, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
    print({c: len(v) for c, v in sorted(by_category.items())}, sum(len(v) for v in by_category.values()))


if __name__ == '__main__':
    main(sys.argv[1])
