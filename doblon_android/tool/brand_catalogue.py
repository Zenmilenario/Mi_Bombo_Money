"""Regenerates the brand catalogue for both apps from the OpenStreetMap Name Suggestion Index (BSD-3, see
third_party/name-suggestion-index/LICENSE.md):
- lib/brand_catalogue.dart (Android and the future Flutter iPhone app)
- ../MiPatrimonio/Core/Services/BrandCatalogue.swift (current iPhone app)

Usage: python tool/brand_catalogue.py <folder with the NSI data/brands JSON files, named like shop_clothes.json>
Download each file from https://raw.githubusercontent.com/osmlab/name-suggestion-index/main/data/brands/<group>/<type>.json

Kept: brands present in Spain or worldwide/Europe ("es", "001", "150"), mapped to Doblón's starter categories,
and only when the brand belongs to a single category (Carrefour, a supermarket and a petrol station, is left out).
The apps consult it only when the category model has no proposal (it never changes a proposal the model makes):
the experiment of 12/11/2026 (Obsidian, «IA de clasificación de movimientos») showed that adding the brands as training
examples took away correct proposals for categories without brands.
"""
import glob
import json
import os
import re
import sys

CATEGORY = {
    'supermarket': 'Supermercado', 'shop_supermarket': 'Supermercado', 'shop_convenience': 'Supermercado',
    'amenity_restaurant': 'Restaurantes', 'amenity_fast_food': 'Restaurantes', 'amenity_cafe': 'Restaurantes',
    'amenity_bar': 'Restaurantes', 'amenity_ice_cream': 'Restaurantes',
    'amenity_fuel': 'Coche', 'shop_car_repair': 'Coche', 'shop_tyres': 'Coche',
    'amenity_pharmacy': 'Farmacia', 'shop_optician': 'Salud',
    'shop_clothes': 'Ropa', 'shop_shoes': 'Ropa',
    'shop_electronics': 'Compras', 'shop_department_store': 'Compras', 'shop_doityourself': 'Compras',
    'shop_furniture': 'Compras', 'shop_sports': 'Compras', 'shop_toys': 'Compras', 'shop_books': 'Compras',
    'shop_variety_store': 'Compras', 'shop_chemist': 'Compras', 'shop_cosmetics': 'Compras', 'shop_perfumery': 'Compras',
    'shop_pet': 'Mascotas', 'shop_mobile_phone': 'Internet y móvil', 'amenity_cinema': 'Ocio', 'tourism_hotel': 'Viajes',
}
REGIONS = {'es', '001', '150'}
# A one-word brand that is also an ordinary word would match unrelated concepts («METRO DE MADRID», «CAFE EXPRESS»).
COMMON = {'metro', 'plaza', 'super', 'centro', 'center', 'express', 'market', 'mercado', 'city', 'local', 'casa', 'home',
          'auto', 'moda', 'total', 'basic', 'box', 'plus', 'store', 'shop', 'one', 'go', 'top', 'star', 'sol', 'mar'}
FOLD = str.maketrans('áàâäãéèêëíìîïóòôöõúùûüñç', 'aaaaaeeeeiiiiooooouuuunc')


def words(text):
    return re.findall(r'[^\W\d_]+', text.lower().translate(FOLD))
HERE = os.path.dirname(os.path.abspath(__file__))
HEADER = 'Generated by doblon_android/tool/brand_catalogue.py from the OpenStreetMap Name Suggestion Index.'
LICENSE = 'Copyright name-suggestion-index contributors, BSD 3-Clause: doblon_android/third_party/name-suggestion-index/LICENSE.md'
DOC = 'Real brands present in Spain, by Doblón starter category. Consulted only when the category model has no proposal.'


def catalogue(folder):
    found = {}
    for path in glob.glob(os.path.join(folder, '*.json')):
        category = CATEGORY.get(os.path.basename(path)[:-5])
        if not category:
            continue
        with open(path, encoding='utf-8') as source:
            items = json.load(source).get('items', [])
        for item in items:
            if not REGIONS & {str(x) for x in item.get('locationSet', {}).get('include', [])}:
                continue
            tags = item.get('tags', {})
            name = (tags.get('brand') or tags.get('name') or item.get('displayName') or '').strip()
            # The brand is looked up by its whole words: a single short or ordinary word is too risky.
            parts = words(name)
            if parts and (len(parts) > 1 or (len(parts[0]) >= 4 and parts[0] not in COMMON)):
                found.setdefault(name, set()).add(category)
    by_category = {}
    for name, categories in found.items():
        if len(categories) == 1:
            by_category.setdefault(next(iter(categories)), []).append(name)
    return {c: sorted(names, key=str.lower) for c, names in sorted(by_category.items())}


def literal(name, dart):
    # A JSON string is a valid Dart or Swift string literal (no \u escapes thanks to ensure_ascii=False);
    # Dart also interpolates `$`, so it is escaped there.
    text = json.dumps(name, ensure_ascii=False)
    return text.replace('$', r'\$') if dart else text


def write(path, lines):
    with open(path, 'w', encoding='utf-8', newline='\n') as out:
        out.write('\n'.join(lines) + '\n')


def main(folder):
    brands = catalogue(folder)
    dart = [f'// {HEADER}', f'// {LICENSE}', '// Do not edit by hand.', '', f'/// {DOC}',
            'const brandCatalogue = <String, List<String>>{']
    dart += [f"  '{c}': [{', '.join(literal(n, True) for n in names)}]," for c, names in brands.items()]
    dart.append('};')
    write(os.path.join(HERE, '..', 'lib', 'brand_catalogue.dart'), dart)
    swift = [f'// {HEADER}', f'// {LICENSE}', '// Do not edit by hand.', '', f'/// {DOC}', 'enum BrandCatalogue {',
             '    static let brands: [String: [String]] = [']
    swift += [f'        "{c}": [{", ".join(literal(n, False) for n in names)}],' for c, names in brands.items()]
    swift += ['    ]', '}']
    write(os.path.join(HERE, '..', '..', 'MiPatrimonio', 'Core', 'Services', 'BrandCatalogue.swift'), swift)
    print({c: len(v) for c, v in brands.items()}, sum(len(v) for v in brands.values()))


if __name__ == '__main__':
    main(sys.argv[1])
